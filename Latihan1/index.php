        <h1>PHP OOP</h1>
        <h2>Apa Itu OOP</h2>
        <p>OOP adalah gaya/paradigma pemrograman, struktur penulisan program dengan objek.</p>
        <h2>Apa Itu Procedural Programming</h2>
        <ul>
            <li>Instruksi dilakukan langkah demi langkah.</li>
            <li>Memecah program menjdi bagian-bagian kecil (Modularisasi).</li>
            <li>Dlm bahasa pemrograman lain, dsbt prosedur, subroutine atau function.</li>
            <li>Linear/Top-to-Bottom.</li>
            <li>Fortran, ALGOL, COBOL, Pascal, C, PHP, JavaScript.</li>
        </ul>
        <h2>Kelebihan Procedural Programming</h2>
        <ul>
            <li>To-the-Point.</li>
            <li>Simplicity & kemudahan implementasi (utk compiler & interpreter).</li>
            <li>Mudah ditelusuri.</li>
            <li>Membutuhkan lebih sedikit memori pd saat proses eksekusi program (dibandingkan dgn OOP).</li>
        </ul>
        <h2>OOP</h2>
        <ul>
            <li>Menyusun semua kode program & struktur data sbg objek.</li>
            <li>Objek adalah unit dasar dari program.</li>
            <li>Objek menyimpan data & perilaku.</li>
            <li>Objek bisa saling berinteraksi.</li>
            <li>Java, Ruby, Python, C++, JavaScript, PHP5.</li>
        </ul>
        <h2>Kelebihan OOP</h2>
        <ul>
            <li>Representasi dunia nyata.</li>
            <li>Enkapsulasi & Abstraksi data. Enkapsulasi memungkinkan data yg dibuat menjdi aman dari sisi tdk bisa diakses sembarangan dari bagian lain di program. Dgn abstraksi data, memudahkan utk menyembunyikan kerumitan dari program.</li>
            <li>Resusability.</li>
            <li>Skalabilitas & Ekstensibilitas.</li>
            <li>Kemudahan pengelolaan.</li>
            <li>Kolaborasi.</li>
            <li>Digunakan oleh framework.</li>
        </ul>
        <h2>Procedural VS Object Oriented</h2>
        <p>Tdk ada yg lebih bagus, masing-masing punya fokunya sendiri.</p>
        <p>Jika membuat program yg simpel, & dikerjakan sendiri, lebih cocok menggunakan paradigma pemrograman prosedural.</p>
        <p>Jika membuat program yg besar, & dikerjakan oleh banyak org, lebih cocok menggunakan paradigma OOP.</p>
        <h2>Konsep OOP Pd PHP</h2>
        <h3>Basic</h3>
        <ul>
            <li>Class & Object.</li>
            <li>Property & Method.</li>
            <li>Constuctor.</li>
            <li>Object Type. Bisa membuat objek sbg tipe data sendiri.</li>
            <li>Inheritance.</li>
            <li>Visibility/Access Modifier.</li>
            <li>Setter & Getter.</li>
            <li>Static Method.</li>
        </ul>
        <h3>Advanced</h3>
        <ul>
            <li>Abstract & Interface</li>
            <li>Interceptor.</li>
            <li>Object Cloning. Bagaimana menduplikasi objek sehingga memiliki perilaku yg beda, tdk membawa perilaku dari objek sebelumnya.</li>
            <li>Callbacks & Closures.</li>
            <li>Namespacing & Autoloading. Begitu menggunakan OOP, kita harus melakukan loading semua kelas yg dibuat kedlm program.</li>
            <li>...</li>
        </ul>
        <h2>Apa Yg Harus Disiapkan</h2>
        <ul>
            <li>Code Editor.</li>
            <li>Web Server.</li>
            <li>Web Browser.</li>
            <li>Database Server.</li>
        </ul>
